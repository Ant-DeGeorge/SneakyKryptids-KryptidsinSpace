# pickup capsules (16x16, FX palette): letter in the middle
def capsule(letter_rows):
    top = [
    "....33333333....",
    "...3222222223...",
    "..321111111123..",
    ".32111111111123.",
    ]
    mid = []
    for r in letter_rows:   # 7 rows, 8 wide, '#' = dark glyph
        g = "".join('3' if c == '#' else '1' for c in r)
        mid.append(".3211" + g[:6] + "1123."[:5])
    bot = [
    ".32111111111123.",
    "..321111111123..",
    "...3222222223...",
    "....33333333....",
    "................",
    ]
    rows = top + mid + bot
    return [r[:16].ljust(16, '.') for r in rows][:16]

