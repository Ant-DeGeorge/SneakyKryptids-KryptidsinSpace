#!/usr/bin/env python3
"""Emit src/weapon_fx2_b5.c (tiles, ROM bank 5) and src/weapon_fx2.h (tile numbers) for the
second weapon-flair set (tools/weapon_fx2.py). Also writes build/preview/weapon_fx2.png.
Run: python3 tools/gen_weapon_fx2.py"""
import os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from gbart import parse, encode
from emit import pal_words
import weapon_fx as W
import weapon_fx2 as W2

BASE, BANK = 80, 5
def rest(p):        # colour 1 snapped to GBC 5-bit steps, exactly as gen_weapon_fx.py's glow step 0
    q = list(p); q[1] = '#%02X%02X%02X' % tuple((int(p[1][i:i + 2], 16) >> 3) << 3 for i in (1, 3, 5)); return q
tiles, defs = [], []
for name, art, w in W2.SPRITES:
    img = parse(art, w)
    assert len(img) == 16, name
    defs.append((name, BASE + len(tiles)))
    for c in range(w // 8):
        tiles.append([row[c * 8:c * 8 + 8] for row in img[:8]])
        tiles.append([row[c * 8:c * 8 + 8] for row in img[8:]])
assert BASE + len(tiles) <= 128, len(tiles)
data = sum((encode(t) for t in tiles), [])
src = os.path.join(HERE, '..', 'src')
open(os.path.join(src, 'weapon_fx2_b5.c'), 'w').write(
    '// Generated by tools/gen_weapon_fx2.py - do not edit.\n#pragma bank 5\n#include <stdint.h>\n'
    f'const uint8_t fx2_tiles[{len(data)}] = {{' + ','.join(map(str, data)) + '};\n'
    # resting weapon colours, for the gun cam (which loads them into OBJ palette 1)
    'const uint16_t fx2_wpn_pals[12] = {' + ','.join('0x%04X' % w for p in W.WEAPON_PALS for w in pal_words(rest(p))) + '};\n')
H = ['// Generated by tools/gen_weapon_fx2.py - do not edit. Weapon flair part 2: OBJ VRAM bank 1 tiles.',
     '#ifndef WEAPON_FX2_H', '#define WEAPON_FX2_H', '#include <stdint.h>',
     f'#define BANK_FX2 {BANK}', f'#define FX2_BASE {BASE}', f'#define FX2_NT {len(tiles)}',
     'extern const uint8_t fx2_tiles[];', 'extern const uint16_t fx2_wpn_pals[];']
H += [f'#define FX_{n} {v}' for n, v in defs]
H += ['#endif', '']
open(os.path.join(src, 'weapon_fx2.h'), 'w').write('\n'.join(H))
print(f'weapon_fx2: {len(W2.SPRITES)} sprites, {len(tiles)} tiles at {BASE}..{BASE + len(tiles) - 1}')

# preview: every sprite in each weapon palette (row per weapon) + palette 7 for capsule/rune art
try:
    from PIL import Image
    hx = lambda s: tuple(int(s[i:i + 2], 16) for i in (1, 3, 5))
    FX7 = ['#000000', '#F8F8F8', '#F8D038', '#E86018']
    pals = [p for p in W.WEAPON_PALS] + [FX7]
    S = 4; W_ = sum(w + 2 for _, _, w in W2.SPRITES)
    im = Image.new('RGB', (W_ * S, len(pals) * 18 * S), (24, 28, 52)); px = im.load()
    for r, pal in enumerate(pals):
        x0 = 0
        for name, art, w in W2.SPRITES:
            for y, row in enumerate(art):
                for x, ch in enumerate(row):
                    if ch != '.':
                        for a in range(S):
                            for b in range(S): px[(x0 + x) * S + a, (r * 18 + y) * S + b] = hx(pal[int(ch)])
            x0 += w + 2
    os.makedirs(os.path.join(HERE, '..', 'build', 'preview'), exist_ok=True)
    im.save(os.path.join(HERE, '..', 'build', 'preview', 'weapon_fx2.png'))
except ImportError:
    pass
