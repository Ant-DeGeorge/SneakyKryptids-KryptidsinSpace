#!/usr/bin/env python3
"""Emit src/weapon_fx3.c and src/weapon_fx3.h: the Arcade weapons' sprites (tools/weapon_fx3.py),
for OBJ VRAM bank 1 from tile 52. Also writes build/preview/weapon_fx3.png. Run: python3 tools/gen_weapon_fx3.py"""
import os, sys
HERE = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, HERE)
from gbart import parse, encode
import weapon_fx3 as W
BASE = 52
tiles, defs = [], []
for name, art, w in W.SPRITES:
    art = [r.ljust(w, '.')[:w] for r in art]
    img = parse(art, w); assert len(img) == 16, name
    defs.append((name, BASE + len(tiles)))
    for c in range(w // 8):
        tiles.append([row[c * 8:c * 8 + 8] for row in img[:8]]); tiles.append([row[c * 8:c * 8 + 8] for row in img[8:]])
assert BASE + len(tiles) <= 80, len(tiles)
data = sum((encode(t) for t in tiles), [])
src = os.path.join(HERE, '..', 'src')
open(os.path.join(src, 'weapon_fx3.c'), 'w').write(
    '// Generated by tools/gen_weapon_fx3.py - do not edit.\n#pragma bank 255\n#include <gb/gb.h>\n#include <stdint.h>\nBANKREF(weapon_fx3)\n'
    f'const uint8_t fx3_tiles[{len(data)}] = {{' + ','.join(map(str, data)) + '};\n')
H = ['// Generated by tools/gen_weapon_fx3.py - do not edit. Arcade weapons: OBJ VRAM bank 1 tiles.',
     '#ifndef WEAPON_FX3_H', '#define WEAPON_FX3_H', '#include <gb/gb.h>', '#include <stdint.h>',
     f'#define FX3_BASE {BASE}', f'#define FX3_NT {len(tiles)}', 'extern const uint8_t fx3_tiles[];', 'BANKREF_EXTERN(weapon_fx3)']
H += [f'#define FX3_{n} {t}' for n, t in defs] + ['#endif', '']
open(os.path.join(src, 'weapon_fx3.h'), 'w').write('\n'.join(H))
print(f'weapon_fx3: {len(W.SPRITES)} sprites, {len(tiles)} tiles at {BASE}..{BASE + len(tiles) - 1}')
from PIL import Image
hx = lambda s: tuple(int(s[i:i + 2], 16) for i in (1, 3, 5))
pals = [['#000000', '#FFFFFF', '#F040F0', '#6010A0'], ['#000000', '#FFFFFF', '#40F0F0', '#1060A0'],
        ['#000000', '#FFFFFF', '#F8E040', '#F04080'], ['#000000', '#F8F8F8', '#F8D038', '#E86018']]
S = 6; Wd = sum(w + 2 for _, _, w in W.SPRITES)
im = Image.new('RGB', (Wd * S, len(pals) * 18 * S), (24, 28, 52)); p = im.load()
for r, pal in enumerate(pals):
    x0 = 0
    for name, art, w in W.SPRITES:
        for y, row in enumerate(art):
            for x, ch in enumerate(row[:w]):
                if ch not in '. ':
                    for a in range(S):
                        for b in range(S): p[(x0 + x) * S + a, (r * 18 + y) * S + b] = hx(pal[int(ch)])
        x0 += w + 2
os.makedirs(os.path.join(HERE, '..', 'build', 'preview'), exist_ok=True)
im.save('/tmp/fx3.png')
