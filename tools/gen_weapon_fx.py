#!/usr/bin/env python3
"""Emit src/weapon_fx.h (weapon flair): weapon OBJ palettes + effect sprite tiles.
Run: python3 tools/gen_weapon_fx.py   (Python 3 only; included by src/stage.c, bank 1)"""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from gbart import parse, encode
from emit import pal_words
import weapon_fx as W

def tiles(rows):
    img = parse(rows, 8)
    assert len(img) == 16
    return encode(img[:8]) + encode(img[8:])

def mix(a, b, k):   # k/4 of the way from a to b, in GBC 5-bit steps
    a = [int(a[i:i+2], 16) >> 3 for i in (1, 3, 5)]; b = [int(b[i:i+2], 16) >> 3 for i in (1, 3, 5)]
    c = [x + (y - x) * k // 4 for x, y in zip(a, b)]
    return '#%02X%02X%02X' % tuple(v << 3 for v in c)

out = ["// Generated by tools/gen_weapon_fx.py - do not edit. Weapon colours + effect sprites.",
       "#ifndef WEAPON_FX_H", "#define WEAPON_FX_H", "#include <stdint.h>"]
# [weapon][glow step 0..2][4 colours]: step 0 = rest, 2 = full max-level shimmer tint on colour 1
words = []
for p, g in zip(W.WEAPON_PALS, W.WEAPON_GLOW):
    for k in (0, 2, 4):
        q = list(p); q[1] = mix(p[1], g, k); words += pal_words(q)
out.append("static const uint16_t wpn_pals[%d] = {%s};" % (len(words), ", ".join("0x%04X" % w for w in words)))
# shots overwrite the common tiles ST_SHOT_TWIN..ST_SHOT_WISP+1 (12-17); new ones go in free tiles 120-127
shots = sum((tiles(r) for r in (W.SHOT_TWIN, W.SHOT_SPREAD, W.SHOT_WISP)), [])
new = sum((tiles(r) for r in (W.SHOT_TWIN2, W.SHOT_SPREAD_B, W.MUZZLE, W.HIT)), [])
out.append("static const uint8_t fx_shot_tiles[%d] = {%s};" % (len(shots), ",".join(str(b) for b in shots)))
out.append("static const uint8_t fx_new_tiles[%d] = {%s};" % (len(new), ",".join(str(b) for b in new)))
out += ["#define FX_FIRST 120", "#define ST_SHOT_TWIN2 120", "#define ST_SHOT_SPREADB 122",
        "#define ST_MUZZLE 124", "#define ST_HIT 126", "#endif", ""]
open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src", "weapon_fx.h"), "w").write("\n".join(out))
print("weapon_fx.h:", len(words), "palette words,", len(shots) + len(new), "tile bytes")
