#!/usr/bin/env python3
"""music/*.uge -> GBDK C for hUGEDriver.

Writes src/music/mus_<song>.c (one per song, each in a ROM bank chosen here), src/music/music_table.c
(ROM0: bank and descriptor of every song) and src/songs.h (MUS_* ids, same order as before).
"""
import os, sys, re
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, '..', '..')
sys.path.insert(0, HERE)
import uge, uge2c
from compose import ORDER

BANKS = [28, 29, 30, 31, 8, 18, 22, 24, 27]       # banks with room (bank 8 held the old music)
CAP = 16384 - 256


def size_estimate(c_src):
    """Bytes the converted song takes in ROM: count the initializer bytes."""
    n = 0
    n += 3 * c_src.count('DN(')
    n += 2 * sum(len(m.group(1).split(',')) for m in re.finditer(r'order\d\[\] = \{([^}]*)\}', c_src))
    n += 7 * len(re.findall(r'^\s+\{[^}]*\},$', c_src, re.M))
    m = re.search(r'waves\[\] = \{([^}]*)\}', c_src)
    n += len([v for v in m.group(1).replace('\n', '').split(',') if v.strip()]) + 32
    return n


def main():
    out = os.path.join(ROOT, 'src', 'music')
    os.makedirs(out, exist_ok=True)
    for f in os.listdir(out):
        if f.startswith('mus_') and f.endswith('.c'): os.remove(os.path.join(out, f))
    free = {b: CAP for b in BANKS}
    table = []
    for key in ORDER:
        song = uge.Song.load(os.path.join(ROOT, 'music', key.lower() + '.uge'))
        name = 'mus_' + key.lower()
        probe = uge2c.render(uge.Song.load(os.path.join(ROOT, 'music', key.lower() + '.uge')), name, 0)
        need = size_estimate(probe)
        bank = next((b for b in BANKS if free[b] >= need), None)
        if bank is None: raise SystemExit(f'{key}: no bank has {need} bytes free')
        free[bank] -= need
        open(os.path.join(out, name + '.c'), 'w').write(uge2c.render(song, name, bank))
        table.append((key, name, bank, need))
    L = ['// generated by tools/music/build_music.py', '#include "../hUGE/hUGEDriver.h"', '#include <stdint.h>']
    L += [f'extern const hUGESong_t {n};' for _, n, _, _ in table]
    L.append('const hUGESong_t * const music_songs[] = {' + ', '.join(f'&{n}' for _, n, _, _ in table) + '};')
    L.append('const uint8_t music_banks[] = {' + ', '.join(str(b) for _, _, b, _ in table) + '};')
    open(os.path.join(out, 'music_table.c'), 'w').write('\n'.join(L) + '\n')
    with open(os.path.join(ROOT, 'src', 'songs.h'), 'w') as f:
        f.write('// generated by tools/music/build_music.py\n#ifndef SONGS_H\n#define SONGS_H\n')
        f.write('enum { ' + ', '.join(f'MUS_{k}' for k in ORDER) + ', MUS_COUNT };\n#endif\n')
    for k, n, b, need in table: print(f'{k:10s} bank {b:2d}  ~{need} bytes')
    print('free:', {b: v for b, v in free.items()})


if __name__ == '__main__':
    main()
