#!/usr/bin/env python3
"""Watcher eyes for the ending (kin of a captured boss) -> src/ending_eyes.h

Each eye is 32x16 px (4x2 BG tiles). Only the left eye is stored; the right eye
reuses the tiles with the BG X-flip attribute. 5 pupil shapes x 3 lid frames
(open, half, shut). Colours: 0 black, 1 glow rim, 2 iris, 3 hot core.
Also writes a 1-tile star dot and a ring preview PNG (build/eyes_preview.png) if Pillow is around.
"""
import math, os, sys
sys.path.insert(0, os.path.dirname(__file__))
from gbart import encode

W, H = 48, 24
TW, TH = W // 8, H // 8
SHAPES = ["bar", "dot", "slit", "hollow", "alien"]


def eye(shape, frame):
    px = [[0] * W for _ in range(H)]
    cx, cy = 23.5, 12.5
    rx, ry = (21.5, 10.8) if shape == "alien" else (22.0, 10.5)
    lid_drop = [0, 6, 99][frame]

    def inside_raw(x, y):
        dx, dy = (x + 0.5 - cx) / rx, (y + 0.5 - cy) / ry
        if dx * dx + dy * dy > 1.0:
            return False
        # angry brow: lid slopes down toward the nose (right side of the left eye)
        lid = (0.8 if shape != "alien" else 1.5) + (x / W) * (13.5 if shape != "alien" else 3.5) + lid_drop
        return y + 0.5 >= lid

    if frame == 2:      # shut: a thin glowing seam along the lower lid
        for x in range(3, W - 3):
            dx = (x + 0.5 - cx) / rx
            if abs(dx) < 0.97:
                y = int(cy + ry * math.sqrt(1 - dx * dx) * 0.55)
                px[y][x] = 1 if abs(dx) > 0.75 else 2
        return px

    def inside2(x, y):     # drop lone spikes on the outline
        if not inside_raw(x, y):
            return False
        return sum(inside_raw(x + a, y + b) for a, b in ((1, 0), (-1, 0), (0, 1), (0, -1))) >= 3
    inside = inside2
    for y in range(H):
        for x in range(W):
            if inside(x, y):
                edge = not all(inside(x + a, y + b) for a, b in ((1, 0), (-1, 0), (0, 1), (0, -1)))
                px[y][x] = 1 if edge else 2
    # hot core / pupil
    for y in range(H):
        for x in range(W):
            if px[y][x] != 2:
                continue
            dx, dy = (x + 0.5 - cx - 2) / 1.5, (y + 0.5 - (cy + 1.5)) / 1.5
            if shape == "bar":
                if abs(dx) < 6 and abs(dy) < 1.2: px[y][x] = 0
                elif abs(dx) < 9 and abs(dy) < 2.6: px[y][x] = 3
            elif shape == "dot":
                d = math.hypot(dx, dy * 1.1)
                if d < 2.6: px[y][x] = 0
                elif d < 4.4: px[y][x] = 3
            elif shape == "slit":
                e = (dx / 1.3) ** 2 + (dy / 5.5) ** 2
                if e < 1: px[y][x] = 0
                elif (dx / 3.6) ** 2 + (dy / 6.5) ** 2 < 1: px[y][x] = 3
            elif shape == "hollow":
                if (dx / 0.9) ** 2 + (dy / 0.9) ** 2 < 1: px[y][x] = 0
                elif (dx / 9) ** 2 + (dy / 3.2) ** 2 < 1: px[y][x] = 3
            elif shape == "alien":
                if (dx / 10) ** 2 + (dy / 4.0) ** 2 < 1: px[y][x] = 3
                if 1.5 < dx < 4.5 and -3.5 < dy < -1.0: px[y][x] = 0   # cold glint
    return px


def tiles_of(px):
    out = []
    for ty in range(TH):
        for tx in range(TW):
            out.append([row[tx * 8:tx * 8 + 8] for row in px[ty * 8:ty * 8 + 8]])
    return out


def main():
    root = os.path.join(os.path.dirname(__file__), "..")
    data = []
    frames = {}
    for s in SHAPES:
        for f in range(3):
            px = eye(s, f)
            frames[(s, f)] = px
            for t in tiles_of(px):
                data += encode(t)
    n = len(data) // 16
    star = [[0] * 8 for _ in range(8)]
    star[3][3] = 3
    star2 = [[0] * 8 for _ in range(8)]
    star2[5][2] = 1
    sdata = encode(star) + encode(star2)
    lines = ["// generated by tools/gen_eyes.py - do not edit",
             f"// 5 shapes x 3 frames x {TW * TH} tiles ({TW}x{TH}, left eye); stars separate",
             f"#define EYE_W {TW}", f"#define EYE_H {TH}", f"#define EYE_FT {TW * TH}",
             f"#define EYE_SHAPE_NT {3 * TW * TH}",
             "static const uint8_t eye_tiles[] = {"]
    for i in range(0, len(data), 16):
        lines.append("    " + ", ".join(f"0x{b:02X}" for b in data[i:i + 16]) + ",")
    lines.append("};")
    lines.append("static const uint8_t star_tiles[] = {" + ", ".join(f"0x{b:02X}" for b in sdata) + "};")
    with open(os.path.join(root, "src", "ending_eyes.h"), "w") as fh:
        fh.write("\n".join(lines) + "\n")
    print("eye tiles:", n)
    try:
        from PIL import Image
        img = Image.new("RGB", (W * 2 * 3 + 60, len(SHAPES) * (H + 6) * 2))
        cols = [(0, 0, 0), (120, 20, 20), (240, 60, 40), (255, 240, 200)]
        for si, s in enumerate(SHAPES):
            for f in range(3):
                px = frames[(s, f)]
                for y in range(H):
                    for x in range(W):
                        c = cols[px[y][x]]
                        for X, Y in ((f * (W * 2 + 8) + x, si * (H + 6) * 2 + y), (f * (W * 2 + 8) + W * 2 - 1 - x, si * (H + 6) * 2 + y)):
                            pass
                        img.putpixel((f * (W * 2 + 8) + x, si * (H + 6) + y), c)
                        img.putpixel((f * (W * 2 + 8) + W * 2 - 1 - x + 4, si * (H + 6) + y), c)
        os.makedirs(os.path.join(root, "build"), exist_ok=True)
        img = img.crop((0, 0, img.width, len(SHAPES) * (H + 6))).resize((img.width * 4, len(SHAPES) * (H + 6) * 4), Image.NEAREST)
        img.save(os.path.join(root, "build", "eyes_preview.png"))
    except ImportError:
        pass


if __name__ == "__main__":
    main()
